-- TransCamaçari — Supabase initial schema (migration 001)
-- Compatible with existing PHP/MySQL schema structure, adapted for Supabase PostgreSQL + RLS.
-- Seguro para reexecução: usa IF NOT EXISTS e ALTER TABLE ... ADD COLUMN IF NOT EXISTS.

-- Enable extensions
CREATE EXTENSION IF NOT EXISTS postgis;

-- Companies (existing table, kept for compatibility)
CREATE TABLE IF NOT EXISTS companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(150) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Profiles / usuarios linked to Supabase Auth (replaces users table for auth)
CREATE TABLE IF NOT EXISTS profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  company_id BIGINT REFERENCES companies (id) ON DELETE SET NULL,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  role TEXT NOT NULL DEFAULT 'operator' CHECK (role IN ('admin', 'operator')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Linhas (bus lines) — cria se não existir; adiciona colunas novas se já existir
CREATE TABLE IF NOT EXISTS linhas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT REFERENCES companies (id) ON DELETE SET NULL,
  codigo VARCHAR(20) NOT NULL,
  nome VARCHAR(150) NOT NULL,
  bairro VARCHAR(120) NOT NULL,
  origem VARCHAR(150) NOT NULL,
  destino VARCHAR(150) NOT NULL,
  categoria TEXT NOT NULL DEFAULT 'sede' CHECK (categoria IN ('sede', 'orla')),
  visivel BOOLEAN NOT NULL DEFAULT TRUE,
  publicado BOOLEAN NOT NULL DEFAULT FALSE,
  origem_dados TEXT DEFAULT 'manual',
  data_importacao TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_linhas_codigo UNIQUE (codigo)
);

-- Adicionar colunas novas se a tabela já existir (schema legado PHP)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'linhas' AND column_name = 'categoria') THEN
    ALTER TABLE linhas ADD COLUMN categoria TEXT NOT NULL DEFAULT 'sede' CHECK (categoria IN ('sede', 'orla'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'linhas' AND column_name = 'publicado') THEN
    ALTER TABLE linhas ADD COLUMN publicado BOOLEAN NOT NULL DEFAULT FALSE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'linhas' AND column_name = 'origem_dados') THEN
    ALTER TABLE linhas ADD COLUMN origem_dados TEXT DEFAULT 'manual';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'linhas' AND column_name = 'data_importacao') THEN
    ALTER TABLE linhas ADD COLUMN data_importacao TIMESTAMPTZ;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_linhas_codigo ON linhas (codigo);
CREATE INDEX IF NOT EXISTS idx_linhas_categoria ON linhas (categoria);
CREATE INDEX IF NOT EXISTS idx_linhas_publicado ON linhas (publicado);

-- Trigger for updated_at
CREATE OR REPLACE FUNCTION trg_linhas_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS linhas_updated_at ON linhas;
CREATE TRIGGER linhas_updated_at
  BEFORE UPDATE ON linhas
  FOR EACH ROW EXECUTE FUNCTION trg_linhas_updated_at();

-- Horarios (structured, not single text field)
CREATE TABLE IF NOT EXISTS horarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linha_id BIGINT NOT NULL REFERENCES linhas (id) ON DELETE CASCADE,
  horario TIME NOT NULL,
  categoria TEXT NOT NULL DEFAULT 'todos' CHECK (categoria IN ('uteis', 'sabado', 'domingo_feriado', 'todos')),
  ordem INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_horario_linha_categoria_ordem UNIQUE (linha_id, categoria, ordem)
);

-- Adicionar colunas novas se a tabela já existir (schema legado PHP)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'horarios' AND column_name = 'categoria') THEN
    ALTER TABLE horarios ADD COLUMN categoria TEXT NOT NULL DEFAULT 'todos' CHECK (categoria IN ('uteis', 'sabado', 'domingo_feriado', 'todos'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'horarios' AND column_name = 'ordem') THEN
    ALTER TABLE horarios ADD COLUMN ordem INT NOT NULL DEFAULT 0;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_horarios_linha ON horarios (linha_id);
CREATE INDEX IF NOT EXISTS idx_horarios_categoria ON horarios (categoria);

-- Itinerary locations (stops/pontos with geocoding source)
CREATE TABLE IF NOT EXISTS itinerary_locais (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linha_id BIGINT NOT NULL REFERENCES linhas (id) ON DELETE CASCADE,
  sentido TEXT NOT NULL DEFAULT 'ida' CHECK (sentido IN ('ida', 'volta')),
  ordem INT NOT NULL DEFAULT 0,
  nome VARCHAR(150) NOT NULL,
  latitude NUMERIC(10, 7) NOT NULL,
  longitude NUMERIC(10, 7) NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'parada' CHECK (tipo IN ('origem', 'parada', 'destino')),
  geocoding_source TEXT,
  geocoded_at TIMESTAMPTZ,
  CONSTRAINT chk_coords CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180),
  CONSTRAINT uq_itin_linha_sentido_ordem UNIQUE (linha_id, sentido, ordem)
);

CREATE INDEX IF NOT EXISTS idx_itinerary_linha ON itinerary_locais (linha_id);
CREATE INDEX IF NOT EXISTS idx_itinerary_sentido ON itinerary_locais (linha_id, sentido);

-- Route geometries (GeoJSON, from OSRM or other router)
CREATE TABLE IF NOT EXISTS route_geometries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linha_id BIGINT NOT NULL REFERENCES linhas (id) ON DELETE CASCADE,
  sentido TEXT NOT NULL DEFAULT 'ida' CHECK (sentido IN ('ida', 'volta')),
  geometry JSONB NOT NULL,
  estado_validacao TEXT NOT NULL DEFAULT 'estimated' CHECK (estado_validacao IN ('estimated', 'needs_review', 'reviewed', 'official')),
  metodo_geracao TEXT,
  data_geracao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  erro TEXT,
  CONSTRAINT uq_route_linha_sentido UNIQUE (linha_id, sentido)
);

CREATE INDEX IF NOT EXISTS idx_route_linha ON route_geometries (linha_id);
CREATE INDEX IF NOT EXISTS idx_route_estado ON route_geometries (estado_validacao);

-- Import metadata (tracks seed/import runs)
CREATE TABLE IF NOT EXISTS import_metadata (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte TEXT NOT NULL,
  data_importacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  linhas_importadas INT NOT NULL DEFAULT 0,
  horarios_importados INT NOT NULL DEFAULT 0,
  rotas_geradas INT NOT NULL DEFAULT 0,
  rotas_erro INT NOT NULL DEFAULT 0,
  observacoes TEXT
);

