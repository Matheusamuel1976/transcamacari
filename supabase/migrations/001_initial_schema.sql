-- Public read access for published linhas and related data
CREATE POLICY "Public can read published linhas" ON linhas
  FOR SELECT TO anon, authenticated
  USING (publicado = TRUE);

CREATE POLICY "Public can read horarios of published linhas" ON horarios
  FOR SELECT TO anon, authenticated
  USING (EXISTS (SELECT 1 FROM linhas WHERE linhas.id = horarios.linha_id AND linhas.publicado = TRUE));

CREATE POLICY "Public can read itinerary_locais of published linhas" ON itinerary_locais
  FOR SELECT TO anon, authenticated
  USING (EXISTS (SELECT 1 FROM linhas WHERE linhas.id = itinerary_locais.linha_id AND linhas.publicado = TRUE));

CREATE POLICY "Public can read route_geometries of published linhas" ON route_geometries
  FOR SELECT TO anon, authenticated
  USING (EXISTS (SELECT 1 FROM linhas WHERE linhas.id = route_geometries.linha_id AND linhas.publicado = TRUE));

CREATE POLICY "Public can read companies" ON companies
  FOR SELECT TO anon, authenticated
  USING (TRUE);

CREATE POLICY "Public can read profiles" ON profiles
  FOR SELECT TO anon, authenticated
  USING (TRUE);

