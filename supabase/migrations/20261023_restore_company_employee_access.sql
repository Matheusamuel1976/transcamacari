BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

ALTER TABLE public.linhas
  ADD COLUMN IF NOT EXISTS escopo_acesso text NOT NULL DEFAULT 'empresa_privada';
ALTER TABLE public.linhas DROP CONSTRAINT IF EXISTS linhas_escopo_acesso_check;
ALTER TABLE public.linhas ADD CONSTRAINT linhas_escopo_acesso_check
  CHECK (escopo_acesso IN ('catalogo_publico', 'empresa_privada'));

-- The documented municipal network remains public; unpublished manual rows remain private.
UPDATE public.linhas SET escopo_acesso = 'catalogo_publico'
WHERE publicado = true AND situacao_rede IN ('vigente', 'historica');
UPDATE public.linhas SET escopo_acesso = 'empresa_privada'
WHERE NOT (publicado = true AND situacao_rede IN ('vigente', 'historica'));

ALTER TABLE public.linhas DROP CONSTRAINT IF EXISTS uq_linhas_codigo;
DROP INDEX IF EXISTS public.uq_linhas_catalogo_codigo;
DROP INDEX IF EXISTS public.uq_linhas_empresa_codigo;
CREATE UNIQUE INDEX uq_linhas_catalogo_codigo ON public.linhas(codigo)
  WHERE escopo_acesso = 'catalogo_publico';
CREATE UNIQUE INDEX uq_linhas_empresa_codigo ON public.linhas(company_id, codigo)
  WHERE escopo_acesso = 'empresa_privada';

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'active';
ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_role_check;
ALTER TABLE public.profiles ADD CONSTRAINT profiles_role_check
  CHECK (role IN ('admin', 'company_admin', 'operator', 'funcionario'));
ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_status_check;
ALTER TABLE public.profiles ADD CONSTRAINT profiles_status_check
  CHECK (status IN ('active', 'pending', 'suspended'));

CREATE TABLE IF NOT EXISTS public.company_access_codes (
  company_id bigint PRIMARY KEY REFERENCES public.companies(id) ON DELETE CASCADE,
  code_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  rotated_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.profile_line_assignments (
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  linha_id bigint NOT NULL REFERENCES public.linhas(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (profile_id, linha_id)
);
CREATE INDEX IF NOT EXISTS idx_profile_line_assignments_linha
  ON public.profile_line_assignments(linha_id);

CREATE TABLE IF NOT EXISTS public.profile_access_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint REFERENCES public.companies(id) ON DELETE SET NULL,
  actor_profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  target_profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  action text NOT NULL,
  meta text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_profile_access_audit_company_created
  ON public.profile_access_audit(company_id, created_at DESC);

ALTER TABLE public.company_access_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profile_line_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profile_access_audit ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.company_access_codes, public.profile_line_assignments,
  public.profile_access_audit FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.profile_line_assignments, public.profile_access_audit TO authenticated;

CREATE OR REPLACE FUNCTION public.transport_company_id()
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$ SELECT company_id FROM public.profiles WHERE id = (SELECT auth.uid()); $$;
CREATE OR REPLACE FUNCTION public.transport_is_company_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$ SELECT EXISTS (
  SELECT 1 FROM public.profiles
  WHERE id = (SELECT auth.uid()) AND role = 'company_admin' AND status = 'active'
); $$;
REVOKE ALL ON FUNCTION public.transport_company_id() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.transport_is_company_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.transport_company_id(), public.transport_is_company_admin() TO authenticated;

-- Protect the public/private boundary even when a forged payload is sent.
CREATE OR REPLACE FUNCTION public.transport_enforce_line_scope()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE p public.profiles%ROWTYPE;
BEGIN
  SELECT * INTO p FROM public.profiles WHERE id = auth.uid();
  IF p.role = 'company_admin' AND p.status = 'active' THEN
    NEW.company_id := p.company_id;
    NEW.escopo_acesso := 'empresa_privada';
    NEW.situacao_rede := 'nao_verificada';
    NEW.fonte_id := NULL;
    NEW.origem_dados := 'empresa';
  END IF;
  RETURN NEW;
END; $$;
REVOKE ALL ON FUNCTION public.transport_enforce_line_scope() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS transport_enforce_line_scope ON public.linhas;
CREATE TRIGGER transport_enforce_line_scope BEFORE INSERT OR UPDATE ON public.linhas
FOR EACH ROW EXECUTE FUNCTION public.transport_enforce_line_scope();

