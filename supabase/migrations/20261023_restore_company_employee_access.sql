CREATE OR REPLACE FUNCTION public.complete_company_registration(company_name text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE uid uuid := auth.uid(); p public.profiles%ROWTYPE; cid bigint; code text;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'Autenticação necessária'; END IF;
  SELECT * INTO p FROM public.profiles WHERE id = uid FOR UPDATE;
  IF p.role = 'company_admin' AND p.company_id IS NOT NULL THEN RETURN jsonb_build_object('company_id', p.company_id); END IF;
  IF p.role <> 'operator' OR p.company_id IS NOT NULL OR length(trim(company_name)) < 2 THEN RAISE EXCEPTION 'Cadastro empresarial inválido'; END IF;
  INSERT INTO public.companies(nome) VALUES (left(trim(company_name),150)) RETURNING id INTO cid;
  UPDATE public.profiles SET company_id=cid, role='company_admin', status='active' WHERE id=uid;
  code := upper(substr(encode(gen_random_bytes(8),'hex'),1,12));
  INSERT INTO public.company_access_codes(company_id,code_hash,rotated_by)
  VALUES(cid,encode(digest(code,'sha256'),'hex'),uid);
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,target_profile_id,action,meta) VALUES(cid,uid,uid,'company.registered',left(trim(company_name),150));
  RETURN jsonb_build_object('company_id',cid,'code',code);
END; $$;

CREATE OR REPLACE FUNCTION public.request_employee_membership(company_code text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE uid uuid := auth.uid(); p public.profiles%ROWTYPE; cid bigint;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'Autenticação necessária'; END IF;
  SELECT * INTO p FROM public.profiles WHERE id=uid FOR UPDATE;
  IF p.role='funcionario' AND p.company_id IS NOT NULL THEN RETURN jsonb_build_object('company_id',p.company_id,'status',p.status); END IF;
  IF p.role <> 'operator' OR p.company_id IS NOT NULL THEN RAISE EXCEPTION 'Perfil não pode solicitar vínculo'; END IF;
  SELECT company_id INTO cid FROM public.company_access_codes WHERE code_hash=encode(digest(upper(trim(company_code)),'sha256'),'hex');
  IF cid IS NULL THEN RAISE EXCEPTION 'Código da empresa inválido'; END IF;
  UPDATE public.profiles SET company_id=cid, role='funcionario', status='pending' WHERE id=uid;
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,target_profile_id,action) VALUES(cid,uid,uid,'team.register');
  RETURN jsonb_build_object('company_id',cid,'status','pending');
END; $$;

CREATE OR REPLACE FUNCTION public.rotate_company_invite()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE uid uuid := auth.uid(); cid bigint; code text;
BEGIN
  IF NOT public.transport_is_company_admin() THEN RAISE EXCEPTION 'Acesso negado'; END IF;
  cid := public.transport_company_id(); code := upper(substr(encode(gen_random_bytes(8),'hex'),1,12));
  INSERT INTO public.company_access_codes(company_id,code_hash,rotated_by) VALUES(cid,encode(digest(code,'sha256'),'hex'),uid)
  ON CONFLICT(company_id) DO UPDATE SET code_hash=excluded.code_hash,created_at=now(),rotated_by=uid;
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,action) VALUES(cid,uid,'invite.regenerated');
  RETURN jsonb_build_object('code',code);
END; $$;

CREATE OR REPLACE FUNCTION public.set_employee_assignments(p_profile_id uuid, p_line_ids bigint[] DEFAULT '{}')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE uid uuid := auth.uid(); cid bigint; expected int; matched int; desired bigint[]; current_ids bigint[];
BEGIN
  IF NOT public.transport_is_company_admin() THEN RAISE EXCEPTION 'Acesso negado'; END IF; cid:=public.transport_company_id();
  IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_profile_id AND company_id=cid AND role='funcionario') THEN RAISE EXCEPTION 'Funcionário inválido'; END IF;
  SELECT COALESCE(array_agg(value ORDER BY value),'{}'::bigint[]) INTO desired FROM (SELECT DISTINCT unnest(COALESCE(p_line_ids,'{}'::bigint[])) AS value) ids;
  expected:=COALESCE(array_length(desired,1),0);
  IF expected <> COALESCE(array_length(p_line_ids,1),0) THEN RAISE EXCEPTION 'Linhas duplicadas não são permitidas'; END IF;
  SELECT count(*) INTO matched FROM public.linhas WHERE id=ANY(desired) AND company_id=cid AND escopo_acesso='empresa_privada';
  IF matched<>expected THEN RAISE EXCEPTION 'Uma ou mais linhas são inválidas'; END IF;
  SELECT COALESCE(array_agg(linha_id ORDER BY linha_id),'{}'::bigint[]) INTO current_ids FROM public.profile_line_assignments WHERE profile_id=p_profile_id;
  IF current_ids = desired THEN RETURN; END IF;
  DELETE FROM public.profile_line_assignments WHERE profile_id=p_profile_id;
  INSERT INTO public.profile_line_assignments(profile_id,linha_id) SELECT p_profile_id,unnest(desired);
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,target_profile_id,action) VALUES(cid,uid,p_profile_id,'team.user.assigned');
END; $$;

CREATE OR REPLACE FUNCTION public.approve_employee(p_profile_id uuid, p_line_ids bigint[] DEFAULT '{}')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE cid bigint;
BEGIN
  IF NOT public.transport_is_company_admin() THEN RAISE EXCEPTION 'Acesso negado'; END IF; cid:=public.transport_company_id();
  IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_profile_id AND company_id=cid AND role='funcionario' AND status IN ('pending','active')) THEN RAISE EXCEPTION 'Solicitação pendente não encontrada'; END IF;
  IF EXISTS(SELECT 1 FROM public.profiles WHERE id=p_profile_id AND status='active') THEN
    PERFORM public.set_employee_assignments(p_profile_id,p_line_ids);
    RETURN;
  END IF;
  PERFORM public.set_employee_assignments(p_profile_id,p_line_ids);
  UPDATE public.profiles SET status='active' WHERE id=p_profile_id;
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,target_profile_id,action) VALUES(cid,auth.uid(),p_profile_id,'team.user.approved');
END; $$;

CREATE OR REPLACE FUNCTION public.reject_employee(p_profile_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE cid bigint;
BEGIN
  IF NOT public.transport_is_company_admin() THEN RAISE EXCEPTION 'Acesso negado'; END IF; cid:=public.transport_company_id();
  IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_profile_id AND company_id=cid AND role='funcionario' AND status='pending') THEN RAISE EXCEPTION 'Solicitação pendente não encontrada'; END IF;
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,target_profile_id,action) VALUES(cid,auth.uid(),p_profile_id,'team.user.rejected');
  DELETE FROM public.profile_line_assignments WHERE profile_id=p_profile_id;
  UPDATE public.profiles SET company_id=NULL,role='operator',status='active' WHERE id=p_profile_id;
END; $$;

CREATE OR REPLACE FUNCTION public.suspend_employee(p_profile_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE cid bigint;
BEGIN
  IF NOT public.transport_is_company_admin() THEN RAISE EXCEPTION 'Acesso negado'; END IF; cid:=public.transport_company_id();
  UPDATE public.profiles SET status='suspended' WHERE id=p_profile_id AND company_id=cid AND role='funcionario';
  IF NOT FOUND THEN RAISE EXCEPTION 'Funcionário não encontrado'; END IF;
  INSERT INTO public.profile_access_audit(company_id,actor_profile_id,target_profile_id,action) VALUES(cid,auth.uid(),p_profile_id,'team.user.suspended');
END; $$;

