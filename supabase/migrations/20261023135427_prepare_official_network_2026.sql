-- Prepara a transição incremental para a rede oficial de 2026.
-- Este arquivo não importa dados e não altera a classificação das linhas existentes.
-- Aplicar antes de supabase/data/official_network_2026.sql, em transação separada.

begin;

create table if not exists public.transport_sources (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  autoridade text not null,
  titulo text not null,
  url text not null,
  pagina_origem text,
  publicado_em date,
  vigencia_inicio date,
  consultado_em date not null,
  sha256 text,
  escopo text not null,
  confiabilidade text not null check (confiabilidade in ('oficial_primaria', 'oficial_complementar', 'cartografica', 'nao_verificada')),
  created_at timestamptz not null default now()
);

alter table public.transport_sources enable row level security;
drop policy if exists "Public can read transport sources" on public.transport_sources;
create policy "Public can read transport sources" on public.transport_sources
  for select to anon, authenticated using (true);
drop policy if exists "Admins manage transport sources" on public.transport_sources;
create policy "Admins manage transport sources" on public.transport_sources
  for all to authenticated
  using ((select public.transport_is_admin()))
  with check ((select public.transport_is_admin()));
grant select on public.transport_sources to anon, authenticated;
grant insert, update, delete on public.transport_sources to authenticated;
grant usage, select on sequence public.transport_sources_id_seq to authenticated;

alter table public.linhas
  add column if not exists situacao_rede text not null default 'nao_verificada',
  add column if not exists modalidade text not null default 'legado',
  add column if not exists vigencia_inicio date,
  add column if not exists vigencia_fim date,
  add column if not exists fonte_id bigint references public.transport_sources(id) on delete set null,
  add column if not exists grau_confirmacao text not null default 'nao_validado',
  add column if not exists atendimentos_principais text,
  add column if not exists observacoes text;

alter table public.linhas drop constraint if exists linhas_situacao_rede_check;
alter table public.linhas add constraint linhas_situacao_rede_check
  check (situacao_rede in ('vigente', 'historica', 'temporaria', 'nao_verificada'));
alter table public.linhas drop constraint if exists linhas_modalidade_check;
alter table public.linhas add constraint linhas_modalidade_check
  check (modalidade in ('regular', 'domingo_feriado', 'especial', 'legado'));
alter table public.linhas drop constraint if exists linhas_grau_confirmacao_check;
alter table public.linhas add constraint linhas_grau_confirmacao_check
  check (grau_confirmacao in ('confirmado_documentalmente', 'estimado_com_evidencias', 'nao_validado'));
alter table public.linhas drop constraint if exists linhas_vigencia_check;
alter table public.linhas add constraint linhas_vigencia_check
  check (vigencia_fim is null or vigencia_inicio is null or vigencia_fim >= vigencia_inicio);

create index if not exists idx_linhas_situacao_publicacao
  on public.linhas (situacao_rede, publicado, visivel);
create index if not exists idx_linhas_fonte on public.linhas (fonte_id);

alter table public.horarios
  add column if not exists partida_de text,
  add column if not exists observacao text,
  add column if not exists fonte_id bigint references public.transport_sources(id) on delete set null,
  add column if not exists chave_fonte text;

alter table public.horarios drop constraint if exists horarios_categoria_check;
alter table public.horarios add constraint horarios_categoria_check
  check (categoria in ('uteis', 'sabado', 'segunda_sabado', 'domingo_feriado', 'todos'));
alter table public.horarios drop constraint if exists horarios_dias_check;
alter table public.horarios add constraint horarios_dias_check
  check (dias in ('uteis', 'sabado', 'domingo', 'domingo_feriado', 'segunda_sabado', 'todos'));
create unique index if not exists uq_horarios_chave_fonte
  on public.horarios (chave_fonte) where chave_fonte is not null;
create index if not exists idx_horarios_fonte on public.horarios (fonte_id);

-- Uma evidência textual oficial pode existir sem coordenada exata. O frontend já
-- exige coordenadas válidas antes de criar marcadores ou solicitar roteamento.
alter table public.itinerary_locais
  alter column latitude drop not null,
  alter column longitude drop not null,
  add column if not exists fonte_id bigint references public.transport_sources(id) on delete set null,
  add column if not exists grau_confirmacao text not null default 'nao_validado',
  add column if not exists evidencia text,
  add column if not exists chave_fonte text;
alter table public.itinerary_locais drop constraint if exists itinerary_locais_grau_confirmacao_check;
alter table public.itinerary_locais add constraint itinerary_locais_grau_confirmacao_check
  check (grau_confirmacao in ('confirmado', 'estimado_com_evidencias', 'nao_validado'));
create unique index if not exists uq_itinerary_chave_fonte
  on public.itinerary_locais (chave_fonte) where chave_fonte is not null;
create index if not exists idx_itinerary_fonte on public.itinerary_locais (fonte_id);

alter table public.route_geometries
  add column if not exists fonte_id bigint references public.transport_sources(id) on delete set null,
  add column if not exists distancia_m numeric,
  add column if not exists maior_distancia_ponto_m numeric,
  add column if not exists observacoes_validacao text,
  add column if not exists chave_fonte text;
alter table public.route_geometries drop constraint if exists route_geometries_metricas_check;
alter table public.route_geometries add constraint route_geometries_metricas_check
  check ((distancia_m is null or distancia_m >= 0) and
         (maior_distancia_ponto_m is null or maior_distancia_ponto_m >= 0));
create unique index if not exists uq_route_chave_fonte
  on public.route_geometries (chave_fonte) where chave_fonte is not null;
create index if not exists idx_route_fonte on public.route_geometries (fonte_id);

-- Evita search_path mutável no trigger legado sem alterar seu comportamento.
alter function public.trg_linhas_updated_at() set search_path = pg_catalog, public;

commit;

