-- TransCamaçari 2.0 — Schema relacional (PostgreSQL 15+, ex.: Supabase)
-- Equivalente ao schema.sql (MySQL). Rode no SQL Editor do Supabase ou via psql.
-- Não contém dados reais de transporte: apenas estrutura. O seed DEMO,
-- explicitamente fictício, está em seed-pg.sql.
-- As sequences geradas chamam-se {tabela}_id_seq (usadas por Database::lastId).

CREATE TABLE IF NOT EXISTS companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(150) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'operator')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_users_company ON users (company_id);

CREATE TABLE IF NOT EXISTS employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
  nome VARCHAR(120) NOT NULL,
  cargo VARCHAR(120) NOT NULL,
  email VARCHAR(190) NULL,
  telefone VARCHAR(30) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_emp_company ON employees (company_id);

CREATE TABLE IF NOT EXISTS linhas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
  codigo VARCHAR(20) NOT NULL,
  nome VARCHAR(150) NOT NULL,
  bairro VARCHAR(120) NOT NULL,
  origem VARCHAR(150) NOT NULL,
  destino VARCHAR(150) NOT NULL,
  visivel SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_linhas_company_codigo UNIQUE (company_id, codigo)
);
CREATE INDEX IF NOT EXISTS idx_linhas_bairro ON linhas (bairro);

-- updated_at automático (equivale ao ON UPDATE CURRENT_TIMESTAMP do MySQL).
CREATE OR REPLACE FUNCTION trg_linhas_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS linhas_updated_at ON linhas;
CREATE TRIGGER linhas_updated_at
  BEFORE UPDATE ON linhas
  FOR EACH ROW EXECUTE FUNCTION trg_linhas_updated_at();

CREATE TABLE IF NOT EXISTS horarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linha_id BIGINT NOT NULL REFERENCES linhas (id) ON DELETE CASCADE,
  horario TIME NOT NULL,
  dias TEXT NOT NULL DEFAULT 'todos' CHECK (dias IN ('uteis', 'sabado', 'domingo', 'todos'))
);
CREATE INDEX IF NOT EXISTS idx_hor_linha ON horarios (linha_id);

CREATE TABLE IF NOT EXISTS pontos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linha_id BIGINT NOT NULL REFERENCES linhas (id) ON DELETE CASCADE,
  ordem INT NOT NULL DEFAULT 0,
  nome VARCHAR(150) NOT NULL,
  latitude NUMERIC(10, 7) NOT NULL,
  longitude NUMERIC(10, 7) NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'parada' CHECK (tipo IN ('origem', 'parada', 'destino')),
  CONSTRAINT chk_coords CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
);
CREATE INDEX IF NOT EXISTS idx_pto_linha_ordem ON pontos (linha_id, ordem);

CREATE TABLE IF NOT EXISTS contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  assunto VARCHAR(150) NOT NULL,
  mensagem TEXT NOT NULL,
  ip VARCHAR(45) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_contact_created ON contact_messages (created_at);

CREATE TABLE IF NOT EXISTS rate_limits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chave VARCHAR(100) NOT NULL UNIQUE,
  janela_inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  tentativas INT NOT NULL DEFAULT 1
);
