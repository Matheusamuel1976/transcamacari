-- TransCamaçari 2.0 — Migração 03: senha inicial, expiração e auditoria (PostgreSQL)
-- Aditiva e segura. Rode no SQL Editor do Supabase.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS must_change_password SMALLINT NOT NULL DEFAULT 0;

ALTER TABLE company_invites
  ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ NULL DEFAULT NULL;

CREATE TABLE IF NOT EXISTS access_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NULL REFERENCES companies (id) ON DELETE CASCADE,
  actor_id BIGINT NULL,
  action VARCHAR(60) NOT NULL,
  target_id BIGINT NULL,
  meta VARCHAR(500) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_audit_company_created ON access_audit (company_id, created_at);
