-- Aditiva e segura: roda sobre o schema-pg.sql sem perder dados.
-- Rode no SQL Editor do Supabase.

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check
  CHECK (role IN ('admin', 'operator', 'funcionario'));

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'pending')),
  ADD COLUMN IF NOT EXISTS employee_id BIGINT NULL REFERENCES employees (id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS company_invites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL UNIQUE REFERENCES companies (id) ON DELETE CASCADE,
  code VARCHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS line_assignments (
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  linha_id BIGINT NOT NULL REFERENCES linhas (id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, linha_id)
);
CREATE INDEX IF NOT EXISTS idx_asg_linha ON line_assignments (linha_id);
